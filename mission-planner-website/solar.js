  /* spectral irradiance, watts per square metre per electron volt.
     The running total differenced across one bin, which is what the running
     total was built from. */
  function spectral(e) {
    if (e < E0 || e > EMAX - DE) return 0;
    return (powerAbove(e) - powerAbove(e + DE)) / DE;
  }

  /* Radiative dark current, amps per square metre. Exact, six terms is far
     more than enough because Eg/kT is never below about 11. */
  function j0(eg) {
    var x0 = eg / VT, s = 0;
    for (var k = 1; k <= 6; k++) {
      s += Math.exp(-k * x0) * (x0 * x0 / k + 2 * x0 / (k * k) + 2 / (k * k * k));
    }
    return K0 * s;
  }

  /* The most power a diode with this photocurrent and this dark current can
     give, found by narrowing on the maximum rather than by a fitted formula. */
  function mpp(jsc, dark) {
    if (!(jsc > 0) || !(dark > 0)) return { p: 0, v: 0, j: 0, voc: 0 };
    var voc = VT * Math.log(jsc / dark + 1);
    var lo = 0, hi = voc, a, b;
    function pow(v) { return v * (jsc - dark * Math.expm1(v / VT)); }
    for (var i = 0; i < 60; i++) {
      a = lo + (hi - lo) / 3; b = hi - (hi - lo) / 3;
      if (pow(a) < pow(b)) lo = a; else hi = b;
    }
    var v = (lo + hi) / 2;
    return { p: pow(v), v: v, j: jsc - dark * Math.expm1(v / VT), voc: voc };
  }

  /* One junction. Efficiency in per cent. */
  function single(eg) {
    var jsc = Q * fluxAbove(eg);
    var m = mpp(jsc, j0(eg));
    return {
      eta: m.p / PIN * 100,
      jsc: jsc, voc: m.voc, vmp: m.v, jmp: m.j,
      ff: m.voc > 0 && jsc > 0 ? m.p / (m.voc * jsc) : 0
    };
  }

  /* Where the power goes, as three shares of the incoming sunlight that add
     to exactly one hundred. The third is the ultimate efficiency, which is
     the ceiling before any of the voltage losses are taken off. */
  function losses(eg) {
    var pa = powerAbove(eg);
    var harvest = eg * Q * fluxAbove(eg);
    return {
      below: (PIN - pa) / PIN * 100,
      thermal: (pa - harvest) / PIN * 100,
      ultimate: harvest / PIN * 100
    };
  }

  /* Two junctions, wired in series, which is how nearly every real tandem is
     built. The same current has to pass through both, so the pair is solved
     for the current that gives the most total power rather than each cell
     being optimised on its own. The top cell takes everything above its gap,
     the bottom cell gets what the top one let through. */
  function tandem(top, bot) {
    if (!(bot < top)) return { eta: 0, j: 0, v: 0, vtop: 0, vbot: 0, limited: "" };
    var j1 = Q * fluxAbove(top);
    var j2 = Q * (fluxAbove(bot) - fluxAbove(top));
    var d1 = j0(top), d2 = j0(bot);
    var cap = Math.min(j1, j2);
    function volts(j) {
      var a = (j1 - j) / d1 + 1, b = (j2 - j) / d2 + 1;
      if (a <= 0 || b <= 0) return null;
      return { vtop: VT * Math.log(a), vbot: VT * Math.log(b) };
    }
    function pow(j) { var v = volts(j); return v ? j * (v.vtop + v.vbot) : -1; }
    var lo = 0, hi = cap, a, b;
    for (var i = 0; i < 80; i++) {
      a = lo + (hi - lo) / 3; b = hi - (hi - lo) / 3;
      if (pow(a) < pow(b)) lo = a; else hi = b;
    }
    var j = (lo + hi) / 2, v = volts(j);
    if (!v) return { eta: 0, j: 0, v: 0, vtop: 0, vbot: 0, limited: "" };
    return {
      eta: j * (v.vtop + v.vbot) / PIN * 100,
      j: j, v: v.vtop + v.vbot, vtop: v.vtop, vbot: v.vbot,
      jtop: j1, jbot: j2,
      limited: j1 < j2 ? "top" : "bottom"
    };
  }

  return {
    E0: E0, DE: DE, EMAX: EMAX, PIN: PIN, VT: VT,
    fluxAbove: fluxAbove, powerAbove: powerAbove, spectral: spectral,
    j0: j0, single: single, tandem: tandem, losses: losses
  };
