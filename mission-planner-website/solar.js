  var EMAX = E0 + (NA.length - 1) * DE;

  function look(tab, e) {
    if (e <= E0) return tab[0];
    if (e >= EMAX) return tab[tab.length - 1];
    var x = (e - E0) / DE, i = Math.floor(x), f = x - i;
    return tab[i] + (tab[i + 1] - tab[i]) * f;
  }

  /* photons per square metre per second with energy above e */
